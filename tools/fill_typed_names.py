def build(table, cols, from_row, n_col, n_row):
    d = os.path.join(ROOT, 'tables', table['name'])
    meta = json.load(open(os.path.join(d, 'grid.json'), encoding='utf-8'))
    if meta['n_col'] != n_col or meta['n_row'] != n_row:
        raise SystemExit('%s 版式对不上：grid.json 是 %d 列 x %d 行，转录按 %d x %d 写的'
                         % (table['name'], meta['n_col'], meta['n_row'], n_col, n_row))
    if len(cols) != n_col:
        raise SystemExit('%s 转录了 %d 列，grid.json 是 %d 列' % (table['name'], len(cols), n_col))
    grid = []
    for ci, names in enumerate(cols, 1):
        col = [None] * (from_row - 1) + list(names)
        if len(col) > n_row:
            raise SystemExit('%s 第 %d 列：转录 %d 个（从第 %d 行起）-> %d 行，'
                             '超过表的 %d 行（多半是转录时多写或少写了一格，'
                             '后面整列都会错位）' % (table['name'], ci, len(names), from_row,
                                                   len(col), n_row))
        if len(col) < n_row:
            print('    第 %d 列：转录 %d 个，末尾 %d 行留空'
                  % (ci, len(names), n_row - len(col)))
            col += [None] * (n_row - len(col))
        grid.append(col)
    out = dict(table)
    out['col_labels'] = table['col_labels']
    out['cols'] = grid
    out['updated'] = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
    json.dump(out, open(os.path.join(d, 'names.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    total = sum(1 for c in grid for x in c if x)
    print('  %s：%d 列 x %d 行，%d 个商品名 -> tables/%s/names.json'
          % (table['name'], n_col, n_row, total, table['name']))


